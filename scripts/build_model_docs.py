#!/usr/bin/env python3
"""Write docs/models.md from the committed model metadata.

The page lists every task in ``catalog/structures.json`` with its modality, the
exported structure contract, the licence text and the upstream reference.
Whether a task can run is not listed: that depends on the installed runtime,
model assets, licence keys and orientation evidence of a deployment, and the
portal reports it live through ``GET /api/v1/models``.

Usage::

    python scripts/build_model_docs.py          # rewrite docs/models.md
    python scripts/build_model_docs.py --check  # exit 1 with a diff when stale
"""
from __future__ import annotations

import argparse
import collections
import difflib
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "models.md"
TOTALSEGMENTATOR = "https://github.com/wasserth/TotalSegmentator"


def load_app():
    os.environ.setdefault("PORTAL_DATA", tempfile.mkdtemp(prefix="rtseg-model-docs-"))
    sys.path.insert(0, str(ROOT))
    import app  # noqa: PLC0415 - the portal module owns the model metadata

    return app


def cell(value) -> str:
    return " ".join(str(value).split()).replace("|", "\\|")


def licence(details: dict, totalsegmentator: bool) -> str:
    raw = details.get("license")
    if isinstance(raw, dict):
        text = "; ".join(f"{key}: {raw[key]}" for key in ("code", "weights") if raw.get(key))
    elif raw:
        text = str(raw)
    elif details.get("code_license") or details.get("weights_license"):
        text = f"Code: {details.get('code_license', 'not stated')}; weights: {details.get('weights_license', 'not stated')}"
    elif details.get("license_note"):
        text = str(details["license_note"])
    elif totalsegmentator:
        text = "TotalSegmentator terms; some tasks need a licence key"
    else:
        text = "Not recorded in the catalog; see the reference"
    if details.get("noncommercial") and "non-commercial" not in text.lower() and "noncommercial" not in text.lower():
        text += " (non-commercial)"
    return text


def build(app) -> str:
    catalog = app.STRUCTURE_CATALOG
    rows, roles, modalities = [], collections.Counter(), collections.Counter()
    for name in sorted(catalog, key=str.lower):
        contract = catalog[name]
        external = name in app.EXTERNAL_TASKS
        informational = name in app.INFORMATIONAL_MODELS
        details = {**app.model_details(name), **app.NODAL_MODEL_DETAILS.get(name, {})}
        totalsegmentator = not external and not informational
        modality = details.get("modality") or app.task_modality(name)
        kind = contract["kind"]
        structures = f"{kind} ({contract['count']})" if contract.get("count") is not None else kind
        if informational:
            role = "informational: " + str(details.get("blocked_status") or details.get("status") or "listed")
            roles["informational or blocked"] += 1
        elif kind == "unresolved":
            role = "no exporter label contract"
            roles["no exporter label contract"] += 1
        else:
            role = "segmentation task" if kind != "report" else "report task"
            roles[role] += 1
        modalities[modality] += 1
        reference = details.get("reference") or (TOTALSEGMENTATOR if totalsegmentator else "")
        link = f"[link]({reference})" if str(reference).startswith("http") else cell(reference)
        rows.append(f"| `{name}` | {cell(modality)} | {cell(structures)} | {cell(licence(details, totalsegmentator))} "
                    f"| {link} | {cell(role)} |")
    lines = [
        "# Model catalog",
        "",
        "<!-- Generated by scripts/build_model_docs.py from catalog/structures.json and the portal's model",
        "     metadata. Do not edit by hand. -->",
        "",
        f"The committed catalog describes {len(catalog)} tasks. Availability on a given portal depends on its",
        "installed runtime, model assets, licence keys and recorded orientation evidence; `GET /api/v1/models`",
        "reports it live, together with the reason a task is disabled.",
        "",
        "Structure kinds: *fixed* tasks export a known label list (the count is the number of possible ROIs;",
        "only structures found in a scan are written), *variable* tasks name ROIs from the input, *prompted*",
        "tasks segment the target given by points, a box or text, and *report* tasks produce a document instead",
        "of contours. *Unresolved* entries have no exporter label contract and cannot be run.",
        "",
        "| Role | Tasks |",
        "| --- | ---: |",
        *(f"| {role} | {count} |" for role, count in sorted(roles.items())),
        "",
        "| Modality | Tasks |",
        "| --- | ---: |",
        *(f"| {cell(modality)} | {count} |" for modality, count in sorted(modalities.items())),
        "",
        "Licences cover model code and weights as stated by their authors; the RTsegmentator licence does not",
        "grant rights to any model. The [external model ledger](external-models.md) records the evidence and",
        "terms behind each entry.",
        "",
        "| Task | Modality | Structures | Licence | Reference | Catalog role |",
        "| --- | --- | --- | --- | --- | --- |",
        *rows,
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="Fail with a diff when docs/models.md is stale")
    args = parser.parse_args(argv)
    text = build(load_app())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                                       "docs/models.md", "generated"))
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
